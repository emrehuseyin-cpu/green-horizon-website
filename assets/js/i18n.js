let currentLang = localStorage.getItem('gh_lang') || 'en';

function initI18n() {
  const langBtn = document.getElementById('lang-switch-btn');
  const langMenu = document.getElementById('lang-switch-menu');

  if (langBtn && langMenu) {
    langBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      const isOpen = langMenu.classList.contains('open');
      langMenu.classList.toggle('open', !isOpen);
      langBtn.classList.toggle('open', !isOpen);
      langBtn.setAttribute('aria-expanded', String(!isOpen));
    });

    document.addEventListener('click', (e) => {
      if (!langBtn.contains(e.target) && !langMenu.contains(e.target)) {
        langMenu.classList.remove('open');
        langBtn.classList.remove('open');
        langBtn.setAttribute('aria-expanded', 'false');
      }
    });

    langMenu.querySelectorAll('.lang-item-btn').forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        const selected = btn.getAttribute('data-lang');
        setLanguage(selected);
        langMenu.classList.remove('open');
        langBtn.classList.remove('open');
        langBtn.setAttribute('aria-expanded', 'false');
      });
    });
  }

  // Handle mobile drawer language buttons
  document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const selected = btn.getAttribute('data-lang');
      setLanguage(selected);
    });
  });

  // Apply current language on initial load
  applyLanguage(currentLang);
}

function setLanguage(lang) {
  if (!i18nTranslations[lang]) return;
  currentLang = lang;
  localStorage.setItem('gh_lang', lang);
  applyLanguage(lang);
  window.dispatchEvent(new CustomEvent('gh_language_changed', { detail: { lang } }));
}

function applyLanguage(lang) {
  const dict = i18nTranslations[lang] || i18nTranslations.en;

  // Set HTML lang attribute
  document.documentElement.setAttribute('lang', lang);

  // Update top button flag & code
  const activeCodeEl = document.getElementById('current-lang-code');
  if (activeCodeEl) activeCodeEl.textContent = dict.lang_code;

  const activeFlagEl = document.getElementById('current-lang-flag');
  if (activeFlagEl) activeFlagEl.textContent = dict.lang_flag;

  // Update active state in desktop dropdown
  document.querySelectorAll('.lang-item-btn').forEach(btn => {
    const isTarget = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('active', isTarget);
    btn.setAttribute('aria-selected', String(isTarget));
  });

  // Update active state in mobile drawer buttons
  document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
    const isTarget = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('active', isTarget);
  });

  // 1. Automatically translate desktop nav links & mobile nav links
  document.querySelectorAll('.nav-link, .mobile-nav-link').forEach(link => {
    const href = (link.getAttribute('href') || '').toLowerCase().trim();
    const isMobile = link.classList.contains('mobile-nav-link');

    if (href === '/' || href === 'index.html' || href === '' || href === '#') {
      link.textContent = dict.nav_home;
    } else if (href.includes('about')) {
      link.textContent = isMobile ? dict.nav_about_long : dict.nav_about;
    } else if (href.includes('partners')) {
      link.textContent = isMobile ? dict.nav_partners_long : dict.nav_partners;
    } else if (href.includes('activities')) {
      link.textContent = isMobile ? dict.nav_activities_long : dict.nav_activities;
    } else if (href.includes('gallery')) {
      link.textContent = isMobile ? dict.nav_gallery_long : dict.nav_gallery;
    } else if (href.includes('stories')) {
      link.textContent = isMobile ? dict.nav_stories_long : dict.nav_stories;
    } else if (href.includes('exhibition')) {
      link.textContent = isMobile ? dict.nav_exhibition_long : dict.nav_exhibition;
    } else if (href.includes('resources')) {
      link.textContent = isMobile ? dict.nav_resources_long : dict.nav_resources;
    } else if (href.includes('news')) {
      link.textContent = isMobile ? dict.nav_news_long : dict.nav_news;
    } else if (href.includes('contact')) {
      link.textContent = isMobile ? dict.nav_contact_long : dict.nav_contact;
    } else if (href.includes('results')) {
      link.textContent = dict.nav_results;
    }
  });

  // 2. Translate Brand Tagline
  document.querySelectorAll('.site-brand-tagline').forEach(el => {
    el.textContent = dict.brand_tagline;
  });

  // 3. Translate Header Controls & Accessibility
  document.querySelectorAll('.skip-link').forEach(el => {
    el.textContent = dict.skip_link;
  });
  document.querySelectorAll('.mobile-nav-toggle span').forEach(el => {
    el.textContent = dict.menu_btn;
  });
  document.querySelectorAll('.mobile-lang-title').forEach(el => {
    el.textContent = dict.lang_select_title;
  });

  // 4. Translate Footer Chrome
  document.querySelectorAll('.footer-disclaimer-text').forEach(el => {
    el.textContent = dict.footer_disclaimer;
  });
  document.querySelectorAll('.footer-project-number').forEach(el => {
    el.innerHTML = `${dict.footer_project_number_label} <strong>${dict.footer_project_number}</strong>`;
  });

  // Footer Column Headers & Links
  document.querySelectorAll('.footer-col h4').forEach(h4 => {
    const text = h4.textContent.trim().toLowerCase();
    if (text.includes('quick') || text.includes('hızlı') || text.includes('rapide') || text.includes('schnell')) {
      h4.textContent = dict.footer_quick_links;
    } else if (text.includes('legal') || text.includes('yasal') || text.includes('recht')) {
      h4.textContent = dict.footer_legal;
    } else if (text.includes('contact') || text.includes('iletişim') || text.includes('kontakt')) {
      h4.textContent = dict.nav_contact;
    }
  });

  document.querySelectorAll('.footer-links a').forEach(a => {
    const href = (a.getAttribute('href') || '').toLowerCase().trim();
    if (href === '/' || href === 'index.html') a.textContent = dict.nav_home;
    else if (href.includes('about')) a.textContent = dict.nav_about_long;
    else if (href.includes('partners')) a.textContent = dict.nav_partners_long;
    else if (href.includes('activities')) a.textContent = dict.nav_activities_long;
    else if (href.includes('gallery')) a.textContent = dict.nav_gallery_long;
    else if (href.includes('stories')) a.textContent = dict.nav_stories;
    else if (href.includes('exhibition')) a.textContent = dict.nav_exhibition_long;
    else if (href.includes('resources')) a.textContent = dict.nav_resources_long;
    else if (href.includes('news')) a.textContent = dict.nav_news_long;
    else if (href.includes('contact')) a.textContent = dict.nav_contact_long;
    else if (href.includes('results')) a.textContent = dict.nav_results;
    else if (href.includes('privacy')) a.textContent = dict.footer_privacy;
    else if (href.includes('accessibility')) a.textContent = dict.footer_accessibility;
  });

  // Footer Bottom Legal Links & Copyright
  document.querySelectorAll('.footer-bottom-links a').forEach(a => {
    const href = (a.getAttribute('href') || '').toLowerCase();
    if (href.includes('privacy')) a.textContent = dict.footer_privacy;
    if (href.includes('accessibility')) a.textContent = dict.footer_accessibility;
  });
  document.querySelectorAll('.footer-bottom-legal p').forEach(p => {
    if (p.textContent.includes('©')) {
      p.textContent = dict.footer_rights;
    }
  });

  // 5. Translate Common Buttons
  document.querySelectorAll('.btn').forEach(btn => {
    const text = btn.textContent.trim();
    if (text.includes('Explore Our Mission') || text.includes('Misyonumuzu') || text.includes('Misiunea') || text.includes('Mission entdecken')) {
      btn.textContent = dict.btn_explore;
    } else if (text.includes('Discover Climate') || text.includes('İklim Hikayelerini Keşfedin') || text.includes('Poveștile Climatice') || text.includes('Klimageschichten entdecken')) {
      btn.textContent = dict.btn_discover;
    } else if (text.includes('Read Full Article') || text.includes('Tamamını Oku') || text.includes('articolul complet') || text.includes('Artikel lesen')) {
      btn.innerHTML = dict.btn_read_more;
    } else if (text.includes('Download PDF') || text.includes('Bülteni İndir') || text.includes('Ediția PDF') || text.includes('PDF-Ausgabe')) {
      btn.innerHTML = `<svg viewBox="0 0 24 24" width="16" height="16" fill="none" stroke="currentColor" stroke-width="2" style="margin-right:0.35rem;"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"></path><polyline points="7 10 12 15 17 10"></polyline><line x1="12" y1="15" x2="12" y2="3"></line></svg>${dict.btn_download_pdf}`;
    } else if (text.includes('Return to Homepage') || text.includes('Ana Sayfaya Dön') || text.includes('pagina principală') || text.includes('Zurück zur Startseite')) {
      btn.textContent = dict.btn_return_home;
    } else if (text.includes('Return Home') || text.includes('İnapoi acasă') || text.includes('Zurück zur Startseite →')) {
      btn.innerHTML = dict.btn_return_home_arrow;
    } else if (text.includes('Download Booklet') || text.includes('Kitapçığı İndir') || text.includes('Broșura') || text.includes('Broschüre')) {
      btn.textContent = dict.btn_download_booklet;
    }
  });

  // 6. Translate Filter Buttons
  document.querySelectorAll('.filter-btn, .news-filter-btn, .category-filter-btn, .gallery-filter-btn').forEach(btn => {
    const t = btn.textContent.trim().toLowerCase();
    if (t === 'all' || t === 'tümü' || t === 'toate' || t === 'alle') {
      btn.textContent = dict.filter_all;
    } else if (t.includes('newsletter') || t.includes('bülten') || t.includes('buletin')) {
      btn.textContent = dict.filter_newsletters;
    } else if (t.includes('event') || t.includes('etkinlik') || t.includes('eveniment') || t.includes('veranstaltung')) {
      btn.textContent = dict.filter_events;
    } else if (t.includes('workshop') || t.includes('atölye') || t.includes('atelier')) {
      btn.textContent = dict.filter_workshops;
    } else if (t.includes('storie') || t.includes('hikaye') || t.includes('poveșt') || t.includes('geschicht')) {
      btn.textContent = dict.filter_stories;
    }
  });

  // 7. Translate Search Inputs
  document.querySelectorAll('input[type="search"], input[type="text"]').forEach(input => {
    const ph = (input.getAttribute('placeholder') || '').toLowerCase();
    if (ph.includes('news') || ph.includes('haber') || ph.includes('noutăți') || ph.includes('aktuelles')) {
      input.setAttribute('placeholder', dict.search_news_placeholder);
    } else if (ph.includes('gallery') || ph.includes('galeri') || ph.includes('fotogalerie')) {
      input.setAttribute('placeholder', dict.search_gallery_placeholder);
    } else if (ph.includes('resource') || ph.includes('kaynak') || ph.includes('resurse')) {
      input.setAttribute('placeholder', dict.search_resources_placeholder);
    } else if (ph.includes('search') || ph.includes('ara') || ph.includes('caut') || ph.includes('such')) {
      input.setAttribute('placeholder', dict.search_placeholder);
    }
  });

  // 8. Translate Cookie Preferences Banner
  const cookieBanner = document.getElementById('cookie-consent-banner');
  if (cookieBanner) {
    const titleEl = cookieBanner.querySelector('.cookie-consent-text strong');
    if (titleEl) titleEl.textContent = dict.cookie_title;
    const declineBtn = document.getElementById('cookie-decline-btn');
    if (declineBtn) declineBtn.textContent = dict.cookie_essential;
    const acceptBtn = document.getElementById('cookie-accept-btn');
    if (acceptBtn) acceptBtn.textContent = dict.cookie_accept;
  }

  // 9. Translate explicitly tagged data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Trigger gallery re-init if defined
  if (typeof initActivityGalleries === 'function') {
    initActivityGalleries();
  }
}

document.addEventListener('DOMContentLoaded', initI18n);
